class FakePatch:
    patch_id = "patch_uc_16vd_weighted_st_min_cut_v1"
    gates = ["_051_", "_070_", "_071_", "_075_"]
    boundary_inputs = ["UC_10", "UC_11", "_012_", "_013_", "_014_", "_015_", "_017_"]
    boundary_outputs = ["UC_16VD"]
