def test_strip_to_single_module_removes_flop_model():
    stripped = strip_to_single_module(MAPPED_TEXT, "s382")
    assert "module s382" in stripped
    assert stripped.count("module ") == 1
    assert "module dff" not in stripped
    assert "dff DFF_13" in stripped
