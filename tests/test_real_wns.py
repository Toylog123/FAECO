def test_evaluator_accepts_only_strict_wns_improvement(tmp_path):
    evaluator = RealWnsEvaluator(
        mapped_text=MAPPED_TEXT,
        top_module="s382",
        period=0.5,
        liberty_text=LIB_TEXT,
        baseline_wns=-0.94,
        output_dir=tmp_path,
        critical_instances=["_051_", "_070_", "_071_", "_075_"],
        workers=1,
    )
    with mock.patch("rseco.real_wns.run_opensta_sequential", side_effect=_fake_sta):
        result = evaluator(FakePatch, weights=None)
    assert result["improved"] is True
    assert result["wns"] == -0.83
    assert evaluator.call_log[-1]["accepted"]["instance"] == "_071_"
    assert evaluator.call_log[-1]["accepted"]["kind"] == "R"
    accepted = [t for t in evaluator.trials if t["accepted"]]
    assert len(accepted) == 1
    assert accepted[0]["to_type"] in {
        "sky130_fd_sc_hd__or2_2",
        "sky130_fd_sc_hd__or2_4",
    }


