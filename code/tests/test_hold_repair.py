def test_parse_hold_critical_instances_returns_path_order():
    insts = parse_hold_critical_instances(MIN_STA_TEXT)
    # DFF instances carry a "/" and are excluded; the combinational path cell
    # _059_ is the actionable hold-critical instance.
    assert insts == ["_059_"]


def test_parse_worst_hold_endpoint_and_dff_d_input():
    assert parse_worst_hold_endpoint(MIN_STA_TEXT) == "DFF_2"
    assert dff_d_input_net(MAPPED_TEXT, "DFF_2") == "UC_11"


def test_hold_buffer_candidates_include_fanout1_dff_d_pin():
    cands = hold_buffer_candidates(MAPPED_TEXT, "DFF_2")
    # hold repair adds delay even on fanout-1 nets: the endpoint DFF's D pin
    # must be buffered (unlike setup-time buffer_candidates, which require
    # min_fanout >= 2).
    d_pin_cands = [c for c in cands if c[0] == "D"]
    assert d_pin_cands
    assert all(c[2] in ("sky130_fd_sc_hd__buf_1", "sky130_fd_sc_hd__buf_2") for c in d_pin_cands)
    assert all(c[3].startswith("UC_11__buf_") for c in d_pin_cands)


def test_insert_buffer_chain_builds_series_of_n_buffers():
    chained = insert_buffer_chain(MAPPED_TEXT, "DFF_2", "D", "sky130_fd_sc_hd__buf_1", n=2)
    # exactly 2 new buffer instances appear (the dff model uses dfxtp_1)
    assert chained.count("sky130_fd_sc_hd__buf_1") == 2
    assert "_holdb_DFF_2_D_1" in chained
    assert "_holdb_DFF_2_D_2" in chained
    assert "wire UC_11__hbuf_1;" in chained
    assert "wire UC_11__hbuf_2;" in chained
    assert ".D(UC_11__hbuf_2)" in chained
    assert ".X(UC_11__hbuf_1)" in chained
    assert ".X(UC_11__hbuf_2)" in chained


class FakePatch:
    patch_id = "patch_hold_violation"
    gates = ["_059_"]


def _fake_sta(**kwargs):
    netlist_path = Path(kwargs["netlist_path"])
    text = netlist_path.read_text(encoding="utf-8")
    if "_holdb_" in text:
        # buffered: hold fixed, setup unchanged
        return {
            "slack": -0.94,
            "slack_status": "VIOLATED",
            "wns": -0.94,
            "tns": -5.0,
            "min_slack": 0.05,
            "min_slack_status": "MET",
        }
    return {
        "slack": -0.94,
        "slack_status": "VIOLATED",
        "wns": -0.94,
        "tns": -5.0,
        "min_slack": -0.36,
        "min_slack_status": "VIOLATED",
    }


def test_hold_evaluator_accepts_strict_min_slack_improvement(tmp_path):
    evaluator = HoldRepairEvaluator(
        mapped_text=MAPPED_TEXT,
        top_module="s382",
        period=0.5,
        baseline_min_slack=-0.36,
        output_dir=tmp_path,
        critical_instances=["_059_", "DFF_2"],
        workers=1,
    )
    with mock.patch(
        "rseco.hold_repair.run_opensta_sequential", side_effect=_fake_sta
    ):
        result = evaluator(FakePatch, weights=None)
    assert result["improved"] is True
    assert result["min_slack"] == 0.05
    accepted = [t for t in evaluator.trials if t["accepted"]]
    assert len(accepted) == 1
    assert accepted[0]["kind"] == "B"
    assert "buf_" in accepted[0]["to_type"]


def test_hold_evaluator_reports_not_improved_when_all_worse(tmp_path):
    def worse_sta(**kwargs):
        return {
            "slack": -0.96,
            "slack_status": "VIOLATED",
            "wns": -0.96,
            "tns": -6.0,
            "min_slack": -0.40,
            "min_slack_status": "VIOLATED",
        }

    evaluator = HoldRepairEvaluator(
        mapped_text=MAPPED_TEXT,
        top_module="s382",
        period=0.5,
        baseline_min_slack=-0.36,
        output_dir=tmp_path,
        critical_instances=["_059_", "DFF_2"],
        workers=1,
    )
    with mock.patch(
        "rseco.hold_repair.run_opensta_sequential", side_effect=worse_sta
    ):
        result = evaluator(FakePatch, weights=None)
    assert result["improved"] is False
