"""Tests for the Hold-time repair mode (review shortboard 3: scenario expansion).

The pre-layout ideal-net baseline has no natural hold violations (min slack
is uniformly +0.41 on ITC-99).  To exercise the B (buffer-insertion) strategy
against hold violations we inject a *controlled* hold scenario via
set_clock_uncertainty -hold in the OpenSTA script, then measure candidates
with real STA and accept only strict min-slack improvements.  All tests use
synthetic STA text / a mocked OpenSTA, so the suite runs without WSL.
"""

